#!/usr/bin/env python3
"""Bring SDOJ-Recomp's generated code up to two later upstream rexglue-sdk codegen changes that matter on AArch64.

SDOJ-Recomp ships C++ generated by an older rexglue codegen and the game's XEX is needed to run codegen again, so the
two changes are applied to the generated text instead. Each rewrite produces exactly what the newer codegen emits for
that instruction.

1. Barriers, upstream bd833a2 ("feat(codegen): add sync fences for sync, lwsync, and eieio", 2026-10-01).
   The older codegen emitted nothing for these because x86-64's TSO already orders what lwsync orders. AArch64 does
   not, so after each barrier's comment line this inserts:
     sync   -> std::atomic_thread_fence(std::memory_order_seq_cst);
     lwsync -> std::atomic_thread_fence(std::memory_order_acq_rel);
     eieio  -> std::atomic_thread_fence(std::memory_order_seq_cst);

2. fctiw/fctiwz upper bound, upstream df2743b ("feat: macOS Support", 2026-08-11, src/codegen/builders/
   floating_point.cpp): "f64 > double(INT_MAX)" becomes "f64 >= double(INT_MAX)". simde's portable
   _mm_cvttsd_si32/_mm_cvtsd_si32 (used on AArch64) return INT_MIN for values at INT_MAX, where x86's cvttsd2si and
   the PPC return INT_MAX (SDK ppc_tests fctixz.test_fctiwz_8).

Idempotent: running it again changes nothing.

Usage: update_generated_code.py <generated-dir>
"""

import pathlib
import re
import sys

FENCES = {
    "sync": "\tstd::atomic_thread_fence(std::memory_order_seq_cst);\n",
    "lwsync": "\tstd::atomic_thread_fence(std::memory_order_acq_rel);\n",
    "eieio": "\tstd::atomic_thread_fence(std::memory_order_seq_cst);\n",
}
BARRIER_COMMENT = re.compile(r"^\t// (sync|lwsync|eieio)\s*$")
FCTIW_OLD = re.compile(r"\.f64 > double\(INT_MAX\)\) \? INT_MAX : (simde_mm_cvtt?sd_si32)\(")
FCTIW_NEW = r".f64 >= double(INT_MAX)) ? INT_MAX : \1("


def process(path: pathlib.Path) -> tuple[int, int]:
    lines = path.read_text().splitlines(keepends=True)
    out = []
    fences = 0
    bounds = 0
    for i, line in enumerate(lines):
        line, n = FCTIW_OLD.subn(FCTIW_NEW, line)
        bounds += n
        out.append(line)
        m = BARRIER_COMMENT.match(line)
        if not m:
            continue
        fence = FENCES[m.group(1)]
        if i + 1 < len(lines) and lines[i + 1] == fence:
            continue
        out.append(fence)
        fences += 1
    if fences or bounds:
        path.write_text("".join(out))
    return fences, bounds


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    root = pathlib.Path(sys.argv[1])
    total_fences = 0
    total_bounds = 0
    for path in sorted(root.rglob("*.cpp")):
        fences, bounds = process(path)
        total_fences += fences
        total_bounds += bounds
    print(f"{root}: {total_fences} barrier fences added, {total_bounds} fctiw/fctiwz bounds updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
